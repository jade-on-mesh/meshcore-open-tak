"""Trains the tiny Brighter voice net for Wadamesh TAK standalones.

It replaces VoxBrighten's 12-number rule: from the levels of 10 bands of the
decoded voice over the last 40 ms (40 numbers), it gives the level real speech
would have in each of the 4 added sub-bands. A 40-32-32-4 MLP, about 2,500
weights (10 KB of flash), run once per 10 ms.

Writes output/VoxBrightNet.h (copy it to src/ui-touch/ in Wadamesh TAK), a
report comparing it with the rule on speakers it never saw, and demo clips.
"""
import datetime
import glob
import os
import random

import numpy as np
import torch
import torch.nn as nn

from . import data, dsp

HIDDEN = 32
ENERGY_MATCH = 0.5   # as VoxBrighten's rule (scripts/voice/brighten_ref.py)
RULE_NOW = np.array([   # VoxBrighten's rule as shipped, for comparison
    [-7.835, -0.244, -0.636],
    [-15.876, -0.229, -0.845],
    [-21.726, -0.396, -0.946],
    [-33.911, -0.483, -0.981],
])


class Net(nn.Module):
    def __init__(self, n_in):
        super().__init__()
        self.l1 = nn.Linear(n_in, HIDDEN)
        self.l2 = nn.Linear(HIDDEN, HIDDEN)
        self.l3 = nn.Linear(HIDDEN, 4)

    def forward(self, x):
        return self.l3(torch.tanh(self.l2(torch.tanh(self.l1(x)))))   # (target - m) / 10


def load_split(feat_dir, val_share=0.15, seed=7):
    files = sorted(glob.glob(os.path.join(feat_dir, "*.npz")))
    rng = random.Random(seed)
    rng.shuffle(files)
    n_val = max(2, int(len(files) * val_share))
    pick = lambda fs: {k: np.concatenate([np.load(f)[k] for f in fs]) for k in ("x", "m", "l", "y")}
    return pick(files[n_val:]), pick(files[:n_val]), files[:n_val]


def active(d):
    return d["m"] > dsp.ACTIVE_DB


def energy_gap(y, pred):
    """dB to add to each band so predictions carry real speech's average energy."""
    return 10 * np.log10((10 ** (y / 10)).mean(0)) - 10 * np.log10((10 ** (pred / 10)).mean(0))


def rule_fit(tr):
    a = active(tr)
    X = np.c_[np.ones(a.sum()), (tr["m"] - tr["l"])[a], (tr["l"] + 30)[a]]
    coef = np.linalg.lstsq(X, tr["y"][a], rcond=None)[0].T
    coef[:, 0] += ENERGY_MATCH * energy_gap(tr["y"][a], X @ coef.T)
    return coef


def rule_pred(d, coef):
    return dsp.rule_targets(d["m"], d["l"], coef) - d["m"][:, None]


def rms(pred, d):
    a = active(d)
    return np.sqrt(((pred[a] - d["y"][a]) ** 2).mean(0))


def header(net, bias, report_lines):
    sd = {k: v.detach().cpu().numpy().astype(np.float32) for k, v in net.state_dict().items()}

    def arr(name, a):
        if a.ndim == 1:
            return f"static const float {name}[{a.shape[0]}] = {{" + ", ".join(f"{v:.7g}f" for v in a) + "};\n"
        rows = ",\n  ".join("{" + ", ".join(f"{v:.7g}f" for v in r) + "}" for r in a)
        return f"static const float {name}[{a.shape[0]}][{a.shape[1]}] = {{\n  {rows}}};\n"

    n_in = sd["l1.weight"].shape[1]
    s = [
        "// SPDX-License-Identifier: GPL-3.0-or-later",
        "// The Brighter voice net (VoxBrighten). Generated by MeshCore Open TAK's",
        f"// tools/voice-training on {datetime.date.today()}, from LibriTTS-R (CC-BY-4.0)",
        "// through Codec2. Copy into src/ui-touch/; VoxBrighten uses it instead of its rule.",
        "//",
        *[f"// {r}" for r in report_lines],
        "#pragma once",
        "",
        "#define VOX_BRIGHT_NET 1",
        f"constexpr int kVoxBrightNetContext = {dsp.CONTEXT};   // frames: this one and the ones before",
        f"constexpr int kVoxBrightNetIn = {n_in};        // per frame: m, l, 8 analysis bands, (dB + 50) / 20",
        f"constexpr int kVoxBrightNetHidden = {HIDDEN};",
        "// out[k] * 10 + kVoxBrightNetBias[k] = sub-band k's target, in dB relative to m.",
        "",
        arr("kVoxBrightNetW1", sd["l1.weight"]),
        arr("kVoxBrightNetB1", sd["l1.bias"]),
        arr("kVoxBrightNetW2", sd["l2.weight"]),
        arr("kVoxBrightNetB2", sd["l2.bias"]),
        arr("kVoxBrightNetW3", sd["l3.weight"]),
        arr("kVoxBrightNetB3", sd["l3.bias"]),
        arr("kVoxBrightNetBias", np.asarray(bias, np.float32)),
    ]
    return "\n".join(s)


def demo(net, bias, coef, files, out, device):
    import soundfile as sf
    from scipy.signal import resample_poly
    os.makedirs(out, exist_ok=True)
    wavs = []
    for f in files:
        spk = os.path.basename(f)[:-4]
        wavs += glob.glob(os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(f))),
                                       "librittsr", "**", f"{spk}_*.wav"), recursive=True)[:1]
    for i, p in enumerate(sorted(wavs)[:6]):
        w = dsp.load(p, dsp.RATE)
        w = w / np.abs(w).max() * 0.9
        c8 = dsp.codec2(resample_poly(w, 1, 2), "1200")
        y = dsp.play_out(c8)
        a = dsp.analyse(y)
        with torch.no_grad():
            p_net = net(torch.from_numpy(dsp.net_inputs(a)).to(device)).cpu().numpy() * 10 + bias
        t_net = a["m"][:, None] + p_net
        t_rule = dsp.rule_targets(a["m"], a["l"], coef)
        name = os.path.basename(p)[:-4]
        sf.write(os.path.join(out, f"{name}-1-original.wav"), w, dsp.RATE)
        sf.write(os.path.join(out, f"{name}-2-codec2-1200.wav"), y / 32768, dsp.RATE)
        sf.write(os.path.join(out, f"{name}-3-rule.wav"), dsp.apply_targets(y, a, t_rule) / 32768, dsp.RATE)
        sf.write(os.path.join(out, f"{name}-4-net.wav"), dsp.apply_targets(y, a, t_net) / 32768, dsp.RATE)


def main(root, out, workers, epochs=40):
    feat = data.prepare_bright(root, workers)
    tr, va, va_files = load_split(feat)
    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"  {active(tr).sum():,} training frames, {active(va).sum():,} held-out frames, on {device}")

    coef = rule_fit(tr)
    a_tr, a_va = active(tr), active(va)
    xt = torch.from_numpy(tr["x"][a_tr]).to(device)
    yt = torch.from_numpy(tr["y"][a_tr] / 10).to(device)
    xv = torch.from_numpy(va["x"][a_va]).to(device)
    yv = torch.from_numpy(va["y"][a_va] / 10).to(device)
    torch.manual_seed(0)
    net = Net(xt.shape[1]).to(device)
    with torch.no_grad():
        net.l3.bias.copy_(yt.mean(0))   # start from the average level
    opt = torch.optim.Adam(net.parameters(), lr=2e-3)
    sched = torch.optim.lr_scheduler.CosineAnnealingLR(opt, epochs)
    best, best_sd = 1e9, None
    for ep in range(epochs):
        net.train()
        perm = torch.randperm(xt.shape[0], device=device)
        for i in range(0, perm.numel(), 4096):
            j = perm[i: i + 4096]
            loss = ((net(xt[j]) - yt[j]) ** 2).mean()
            opt.zero_grad()
            loss.backward()
            opt.step()
        sched.step()
        net.eval()
        with torch.no_grad():
            v = float(((net(xv) - yv) ** 2).mean().sqrt() * 10)
        if v < best:
            best, best_sd = v, {k: t.clone() for k, t in net.state_dict().items()}
        print(f"\r  epoch {ep + 1}/{epochs}: held-out error {v:.2f} dB (best {best:.2f})", end="", flush=True)
    print()
    net.load_state_dict(best_sd)
    net.eval()
    with torch.no_grad():
        p_tr = net(torch.from_numpy(tr["x"]).to(device)).cpu().numpy() * 10
        p_va = net(torch.from_numpy(va["x"]).to(device)).cpu().numpy() * 10
    bias = ENERGY_MATCH * energy_gap(tr["y"][a_tr], p_tr[a_tr])
    e_net = rms(p_va + bias, va)
    e_rule = rms(rule_pred(va, coef), va)
    e_now = rms(rule_pred(va, RULE_NOW), va)
    lines = [
        f"Held-out speakers ({len(va_files)}), sub-band level error (dB, 4-5/5-6/6-7/7-8 kHz):",
        "  net:                 " + " ".join(f"{v:5.1f}" for v in e_net),
        "  rule, refitted here: " + " ".join(f"{v:5.1f}" for v in e_rule),
        "  rule as shipped:     " + " ".join(f"{v:5.1f}" for v in e_now),
        f"Training frames: {a_tr.sum():,}.",
    ]
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "VoxBrightNet.h"), "w").write(header(net, bias, lines))
    open(os.path.join(out, "bright-report.txt"), "w").write("\n".join(lines) + "\n\nRule refitted here (a, b, c):\n"
                                                           + "\n".join("  " + ", ".join(f"{v:.3f}" for v in r) for r in coef) + "\n")
    print("\n".join(lines))
    demo(net, bias, coef, va_files, os.path.join(out, "bright-demo"), device)
    print(f"  wrote {os.path.join(out, 'VoxBrightNet.h')} and demo clips in {os.path.join(out, 'bright-demo')}")

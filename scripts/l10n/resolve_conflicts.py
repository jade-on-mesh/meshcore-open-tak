#!/usr/bin/env python3
"""Resolve the merge conflicts feature branches keep hitting, by keeping both sides.

    git merge main            # stops with conflicts in lib/l10n/...
    python3 scripts/l10n/resolve_conflicts.py
    git add lib/l10n untranslated.json && git commit

Two feature branches that each added strings at the same place conflict
there, though both sets of keys belong in the file. For every conflicted file
under lib/l10n/ (app_en.arb and the generated app_localizations*.dart) this
keeps "theirs" then "ours" and repairs the join: the comma between arb
entries, and the `@override` that git counted as shared context and left
above only one side. Keys both sides added (the same string) are kept once.
untranslated.json is regenerated by `flutter gen-l10n`; if it conflicts,
this takes either side, so run gen-l10n (CI does) to refresh it.
Markdown files: where both sides only added list lines (the numbered feature
list in documentation/README.md, the "... is in [X.md]" lines), theirs then
ours, renumbered. Any other conflict is left alone and reported: exits
non-zero if conflict markers remain anywhere.
"""
import json
import os
import re
import subprocess
import sys

# The checkout the command runs in (the workflow runs main's copy of this script
# inside a feature branch's checkout).
ROOT = subprocess.run(['git', 'rev-parse', '--show-toplevel'], capture_output=True, text=True,
                      check=True).stdout.strip()
HUNK = re.compile(r'<<<<<<< [^\n]*\n(.*?)=======\n(.*?)>>>>>>> [^\n]*\n', re.S)


def conflicted():
    out = subprocess.run(['git', 'diff', '--name-only', '--diff-filter=U'], cwd=ROOT, capture_output=True,
                         text=True, check=True).stdout
    return out.split()


def handled(path):
    return path.startswith('lib/l10n/') or path == 'untranslated.json' or path.endswith('.md')


LIST_LINE = re.compile(r'^(\d+)\. |^[-*] ')


def md_join(ours, theirs):
    """Both sides only added list items (the feature list in documentation/README.md,
    "X is in [X.md]" lines): keep theirs, then ours numbered on from theirs."""
    lines_o = [l for l in ours.split('\n') if l.strip()]
    lines_t = [l for l in theirs.split('\n') if l.strip()]
    if not all(LIST_LINE.match(l) or l.rstrip().endswith('.md).') for l in lines_o + lines_t):
        return None
    nums = [int(m.group(1)) for l in lines_t if (m := re.match(r'^(\d+)\. ', l))]
    n = max(nums) if nums else None
    out = list(lines_t)
    for l in lines_o:
        if l in lines_t:
            continue
        m = re.match(r'^(\d+)\. ', l)
        if m and n is not None:
            n += 1
            l = f'{n}. ' + l[m.end():]
        out.append(l)
    return '\n'.join(out) + '\n'


def arb_join(ours, theirs):
    t = theirs.rstrip('\n')
    o = ours.rstrip('\n')
    if not t:
        return ours
    if not o:
        return theirs
    if not t.endswith(','):
        t += ','
    # A key both sides added: keep their copy only.
    keys_t = set(re.findall(r'^  "([^"]+)"\s*:', t, re.M))
    kept, skip = [], False
    for line in o.split('\n'):
        m = re.match(r'^  "([^"]+)"\s*:', line)
        if m:
            skip = m.group(1) in keys_t
        if not skip:
            kept.append(line)
    o = '\n'.join(kept).rstrip(',')
    if not o:
        return t.rstrip(',') + '\n'
    # The hunk's last line keeps its own trailing comma (or lack of one) from ours.
    if ours.rstrip('\n').endswith(','):
        o += ','
    return t + '\n' + o + '\n'


def dart_members(chunk):
    """Split generated Dart into members, each with its leading doc/@override."""
    members, cur = [], []
    in_decl = False   # inside a member's declaration (after its "  String" line)
    body = False      # a method with a { } body
    for line in chunk.split('\n'):
        cur.append(line)
        s = line.rstrip()
        if not in_decl and line.startswith('  String'):
            in_decl = True
            body = s.endswith('{')
        if in_decl and ((body and s == '  }') or (not body and s.endswith(';'))):
            members.append('\n'.join(cur))
            cur, in_decl, body = [], False, False
    rest = '\n'.join(cur)
    return members, rest


def dart_join(ours, theirs, abstract):
    def norm(m):
        m = m.strip('\n')
        if not abstract and not m.lstrip().startswith('@override'):
            m = '  @override\n' + m
        return m
    seen, out = set(), []
    for chunk in (theirs, ours):
        members, rest = dart_members(chunk)
        for m in members:
            name = re.search(r'^  String (?:get )?(\w+)', m, re.M).group(1)
            if name in seen:
                continue
            seen.add(name)
            out.append(norm(m))
        if rest.strip() and rest.strip() != '@override':
            out.append(rest.strip('\n'))
    return '\n\n'.join(out) + '\n'


def resolve(path):
    full = os.path.join(ROOT, path)
    s = open(full).read()
    if path.endswith('.md'):
        def fix_md(m):
            j = md_join(m.group(1), m.group(2))
            return m.group(0) if j is None else j
        s = HUNK.sub(fix_md, s)
    elif path == 'untranslated.json':
        s = HUNK.sub(lambda m: m.group(2), s)
    elif path.endswith('.arb'):
        s = HUNK.sub(lambda m: arb_join(m.group(1), m.group(2)), s)
        json.loads(s)
    else:
        abstract = path.endswith('app_localizations.dart')
        def fix(m):
            joined = dart_join(m.group(1), m.group(2), abstract)
            return joined
        s = HUNK.sub(fix, s)
        # git keeps a shared "@override" above the hunk: don't double it.
        s = re.sub(r'(  @override\n)(?:\s*\n)*(  @override\n)', r'\2', s)
        # Members need a blank line between them.
        s = re.sub(r'(;\n|\n  }\n)(  (?:@override|/// No description))', r'\1\n\2', s)
    open(full, 'w').write(s)
    return '<<<<<<<' not in s


def main():
    files = conflicted()
    if not files:
        print('no conflicts')
        return 0
    ok = True
    for p in files:
        if not handled(p):
            print('NOT HANDLED ' + p)
            ok = False
            continue
        good = resolve(p)
        ok &= good
        print(('resolved ' if good else 'STILL CONFLICTED ') + p)
    return 0 if ok else 1


if __name__ == '__main__':
    sys.exit(main())
